const toId = (value) => value
  .normalize('NFKD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '');

const entry = (brand, model, variant, capacity, type, options = {}) => ({
  id: toId([brand, model, variant, capacity ?? 'capacity-to-confirm'].join('-')),
  brand,
  model,
  variant,
  type,
  battery_capacity_kwh: capacity,
  capacity_is_estimate: Boolean(options.estimate),
  capacity_note: options.note || null,
  // The supplied master list does not give connector details. Avoid guessing,
  // especially for scooters and variant-dependent charging inlets.
  connector_type: 'Confirm vehicle variant',
  image_url: type === '2-Wheeler' ? scooterImage : carImage,
  specification_status: options.estimate || options.note ? 'Needs verification' : 'Reference value; confirm exact trim',
});

